-- TRANSFERBRIDGE 148-club registry. Idempotent; staff records are populated separately
-- only when an identifiable professional and a source can be cited.
create table if not exists public.club_directory (
  id uuid primary key default gen_random_uuid(),
  league text not null,
  country text not null,
  club_name text not null,
  created_at timestamptz not null default now(),
  unique (league, club_name)
);
alter table public.club_directory enable row level security;
drop policy if exists "Public can view club directory" on public.club_directory;
create policy "Public can view club directory" on public.club_directory
  for select to anon, authenticated using (true);
grant select on public.club_directory to anon, authenticated;

